#!/usr/bin/env bash
# =============================================================================
# AgentHQ host setup (Ubuntu) — run ON THE UBUNTU HOST, not in Docker.
#
#   bash /home/mg-12623-8/ai-workbench/hermes/data/agenthq-host-setup.sh
#
# What it does (idempotent — safe to re-run any time):
#   1. Verifies the shared Hermes telemetry file is readable on the host.
#   2. Locates the Ubuntu AgentHQ project (~/Documents/AgentHQ/AgentHQ).
#   3. Checks node >= 22 (node:sqlite requirement).
#   4. Ensures the clone has the Hermes file-tail adapter (git pull --ff-only
#      only if the clone is outdated and the tree is clean).
#   5. Writes durable local config (.env.agenthq) + a one-command launcher
#      (start-agenthq.sh) — no machine paths hardcoded in source.
#   6. Starts the backend on 127.0.0.1:4311 and verifies the connection with a
#      REAL Hermes event: it recomputes the adapter's event hash for the newest
#      JSONL line and confirms that exact event exists in the host database.
#
# Never prints telemetry contents — only line counts, IDs, and status fields.
# =============================================================================
set -u

ok()   { printf '[ OK ] %s\n' "$*"; }
warn() { printf '[WARN] %s\n' "$*" >&2; }
info() { printf '[ .. ] %s\n' "$*"; }
fail() { printf '[FAIL] %s\n' "$*" >&2; exit 1; }

EVENTS="${AGENTHQ_EVENTS_FILE:-$HOME/ai-workbench/hermes/data/projects/AgentHQ/data/hermes-events.jsonl}"
BIND_HOST="${AGENTHQ_HOST:-127.0.0.1}"
BIND_PORT="${AGENTHQ_PORT:-4311}"
BASE="http://$BIND_HOST:$BIND_PORT"

info "Step 1/6: shared telemetry file"
[ -f "$EVENTS" ] || fail "event file not found: $EVENTS (is the Hermes container running?)"
[ -r "$EVENTS" ] || { namei -l "$EVENTS" 2>/dev/null; fail "event file not readable by $(id -un) (uid $(id -u)) — permission chain printed above"; }
LINES=$(wc -l < "$EVENTS")
ok "readable: $EVENTS ($LINES lines)"

info "Step 2/6: locating AgentHQ project"
PROJECT="${AGENTHQ_PROJECT:-$HOME/Documents/AgentHQ/AgentHQ}"
if [ ! -f "$PROJECT/package.json" ]; then
  PROJECT="$(find "$HOME/Documents" -maxdepth 4 -name package.json -exec grep -l '"name": "agenthq"' {} \; 2>/dev/null | head -1 | xargs -r dirname)"
fi
[ -n "$PROJECT" ] && [ -f "$PROJECT/package.json" ] || fail "AgentHQ project not found under ~/Documents (set AGENTHQ_PROJECT=/path and re-run)"
ok "project: $PROJECT"

info "Step 3/6: toolchain"
command -v node >/dev/null 2>&1 || fail "node not found on PATH"
command -v npm  >/dev/null 2>&1 || fail "npm not found on PATH"
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
[ "$NODE_MAJOR" -ge 22 ] || fail "node >= 22 required (app uses node:sqlite); found $(node -v)"
ok "node $(node -v), npm $(npm -v)"

info "Step 4/6: version gate (Hermes file-tail adapter)"
cd "$PROJECT" || fail "cannot enter $PROJECT"
if grep -q "HERMES_EVENTS_FILE" src/server/adapters/hermes.ts 2>/dev/null; then
  ok "adapter present (HEAD $(git rev-parse --short HEAD 2>/dev/null || echo 'git n/a'))"
else
  warn "adapter missing in this clone — updating from origin"
  git fetch origin || fail "git fetch failed (offline? fix network and re-run)"
  if [ -n "$(git status --porcelain 2>/dev/null | head -1)" ]; then
    fail "uncommitted local changes in $PROJECT — commit or stash them, then re-run"
  fi
  git pull --ff-only origin main || fail "git pull --ff-only failed (diverged? resolve manually)"
  grep -q "HERMES_EVENTS_FILE" src/server/adapters/hermes.ts || fail "adapter still missing after pull — report this to Hermes"
  npm install --no-audit --no-fund || fail "npm install failed after update"
  ok "updated to $(git rev-parse --short HEAD)"
fi

info "Step 5/6: durable configuration"
cat > "$PROJECT/.env.agenthq" <<EOF
# Generated by agenthq-host-setup.sh — the saved AgentHQ configuration for this
# machine. start-agenthq.sh sources this automatically; no manual exports needed.
HERMES_EVENTS_FILE=$EVENTS
AGENTHQ_HOST=$BIND_HOST
AGENTHQ_PORT=$BIND_PORT
EOF
cat > "$PROJECT/start-agenthq.sh" <<'EOF'
#!/usr/bin/env bash
# Launch AgentHQ with this machine's saved configuration (.env.agenthq).
set -e
cd "$(dirname "$0")"
set -a; . ./.env.agenthq; set +a
[ -d node_modules ] || npm install --no-audit --no-fund
exec npm start
EOF
chmod +x "$PROJECT/start-agenthq.sh"
ok "wrote .env.agenthq + start-agenthq.sh (npm start equivalent, config remembered)"

info "Step 6/6: start + verify with a real Hermes event"
if curl -s -o /dev/null --max-time 2 "$BASE/api/health"; then
  warn "port $BIND_PORT busy — stopping the previous AgentHQ instance"
  if command -v fuser >/dev/null 2>&1; then
    fuser -k "$BIND_PORT/tcp" 2>/dev/null; sleep 1
  else
    warn "fuser not available — if bind fails, stop the old instance manually"
  fi
fi
: > "$PROJECT/agenthq.log" 2>/dev/null || true
nohup bash "$PROJECT/start-agenthq.sh" >> "$PROJECT/agenthq.log" 2>&1 &
echo $! > "$PROJECT/agenthq.pid"
info "backend starting (pid $(cat "$PROJECT/agenthq.pid"); log: $PROJECT/agenthq.log)"
HEALTH=""
for _ in $(seq 1 30); do
  HEALTH="$(curl -s --max-time 2 "$BASE/api/health" 2>/dev/null || true)"
  case "$HEALTH" in *'"ok":true'*) break ;; esac
  sleep 1
done
case "$HEALTH" in
  *'"ok":true'*) ok "backend up: $BASE" ;;
  *) tail -n 20 "$PROJECT/agenthq.log" >&2; fail "backend did not come up within 30s — see log above" ;;
esac
MODE="$(printf '%s' "$HEALTH" | grep -o '"mode":"[^"]*"' | head -1 | cut -d'"' -f4)"
HERMES_STATE="$(printf '%s' "$HEALTH" | grep -o '"hermes":"[^"]*"' | head -1 | cut -d'"' -f4)"
[ "$HERMES_STATE" = "connected" ] || fail "hermes adapter NOT connected (state: $HERMES_STATE) — see $PROJECT/agenthq.log"
ok "hermes adapter: connected (app mode: ${MODE:-unknown})"

# Exact-event correlation: the adapter derives each DB eventId as
#   'hermes-' + base64url(sha1(writer event_id))
# (the writer's 32-hex ids get redacted, so the adapter hashes the id itself;
# verified against the AgentHQ SQLite store). Recompute it for the newest line
# and require that exact event in the host database.
LAST="$(tail -n 1 "$EVENTS")"
case "$LAST" in
  *'"event_id"'*) : ;;
  *) LAST="$(tail -n 2 "$EVENTS" | head -n 1)" ;;   # skip a torn final line
esac
WID="$(printf '%s' "$LAST" | grep -o '"event_id":"[^"]*"' | head -n 1 | cut -d'"' -f4)"
EXPECTED="hermes-$(printf '%s' "$WID" | openssl dgst -sha1 -binary | basenc --base64url | tr -d '=')"
sleep 3   # let the adapter's 2 s poll ingest the newest line before querying
EVFILE="$(mktemp)"
curl -s --max-time 5 "$BASE/api/events?agentId=hermes&limit=100" > "$EVFILE"
if [ -n "$EXPECTED" ] && grep -q -e "$EXPECTED" -e "$WID" "$EVFILE"; then
  ok "REAL Hermes event verified end-to-end: $EXPECTED (JSONL -> host adapter -> SQLite -> API)"
else
  FILE_TS="$(printf '%s' "$LAST" | grep -o '"ts":"[^"]*"' | head -1 | cut -d'"' -f4)"
  API_TS="$(grep -o '"occurredAt":"[^"]*"' "$EVFILE" | head -1 | cut -d'"' -f4)"
  if [ -n "$FILE_TS" ] && [ -n "$API_TS" ] \
     && [ "$(( $(date -u -d "$API_TS" +%s) - $(date -u -d "$FILE_TS" +%s) ))" -le 120 ]; then
    warn "exact-id match skipped (openssl/basenc?), recency check passed: file ts=$FILE_TS, newest ingested=$API_TS"
  else
    rm -f "$EVFILE"
    fail "no fresh hermes event found in host DB — is the Hermes container still active? (log: $PROJECT/agenthq.log)"
  fi
fi
rm -f "$EVFILE"

echo
echo "=============================================================="
echo "  AgentHQ is LIVE:      $BASE   <- open this in Firefox"
echo "  app mode:             ${MODE:-unknown}   (hermes: connected)"
echo "  start next time:      $PROJECT/start-agenthq.sh"
echo "  stop:                 kill \$(cat $PROJECT/agenthq.pid)"
echo "  logs:                 $PROJECT/agenthq.log"
echo "  re-check / repair:    re-run this script"
echo "=============================================================="
